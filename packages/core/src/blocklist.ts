/** Fold an entry to plain A-Z so it can be matched against grid letters. */
const fold = (word: string) =>
  word
    .normalize("NFD")
    .replace(/\p{M}/gu, "")
    .toUpperCase()
    .replace(/[^A-Z]/g, "");
export const BLOCKLIST: readonly string[] = [
  ...new Set([...ENGLISH, ...SPANISH, ...FRENCH, ...GERMAN].map(fold)),
]
  .filter((w) => w.length >= 3)
  .sort();
